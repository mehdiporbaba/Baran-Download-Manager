const fs = require('node:fs')
const path = require('node:path')
const { render } = require('./release-notes.cjs')
const root = path.resolve(__dirname, '..')
const source = JSON.parse(fs.readFileSync(path.join(root, 'docs/readme.json'), 'utf8'))
const body = '<img src="resources/banner.svg" alt="Baran Download Manager" width="100%" />\n\n' + render(source)
  .replace(`docs/releases/${source.tag}.json`, 'docs/readme.json')
  .replace(/en-v[\d-]+/g, 'en').replace(/fa-v[\d-]+/g, 'fa')
if (process.argv.includes('--write')) fs.writeFileSync(path.join(root, 'README.md'), body)
else if (fs.readFileSync(path.join(root, 'README.md'), 'utf8').replace(/\r\n/g, '\n') !== body) throw Error('README translations are stale; run node scripts/readme.cjs --write')
console.log('Validated complete paired English/Persian README.')
